type Role = 'OWNER' | 'ADMIN' | 'MEMBER';
const EXPECTED_UPDATED_AT = '2026-01-01T00:00:00.000Z';

function tokenFor(role: Role) {
  return `Bearer ${signAccessToken({ userId: 'u1', organisationId: 'org-1', role, sessionId: 'sess-1' })}`;
}

function activeSubscription() {
  return { status: 'ACTIVE', trialEndsAt: null, currentPeriodEnd: new Date(Date.now() + 1_000_000_000) };
}

function authModels(role: Role, subscription: unknown, emailVerified = true) {
  return {
    authSession: { findFirst: async () => ({ id: 'sess-1' }) },
    user: { findUnique: async () => ({ id: 'u1', organisationId: 'org-1', role, emailVerified }) },
    subscription: { findUnique: async () => subscription },
  };
}

type Call = { name: string; args: unknown };

function deadlineRecord(overrides: Record<string, unknown> = {}) {
  return {
    id: 'd1',
    organisationId: 'org-1',
    title: 'Annual report',
    description: null,
    dueDate: new Date('2026-09-30T00:00:00.000Z'),
    scheduleVersion: 1,
    isAutoGenerated: false,
    generatedKind: null,
    generatedKey: null,
    generationVersion: null,
    generationRuleVersion: null,
    generationFingerprint: null,
    generationSource: null,
    generationInputs: null,
    profileRuleKey: null,
    isComplete: false,
    completedDate: null,
    completionDateKnown: true,
    reminderDays: [30, 14, 7],
    supersededAt: null,
    supersededById: null,
    supersessionReason: null,
    archivedAt: null,
    createdAt: new Date('2026-01-01T00:00:00.000Z'),
    updatedAt: new Date('2026-01-01T00:00:00.000Z'),
    ...overrides,
  };
}

/**
 * Builds the deadline app with a spying deadline prisma mock so we can assert
 * which write methods were (not) reached. `deadlineFound` controls findFirst:
 * true => returns an org-1-owned deadline, false => returns null (foreign/missing).
 */
function buildApp(opts: {
  role?: Role;
  clientKind?: 'WEB' | 'MCP_CONNECTOR';
  subscription?: unknown;
  emailVerified?: boolean;
  deadlineFound?: boolean;
  generatedDeadline?: boolean;
  generatedKind?: 'CHARITY_ANNUAL_REPORT' | 'LEGACY_UNVERIFIED';
} = {}) {
  const role = opts.role ?? 'ADMIN';
  const subscription = 'subscription' in opts ? opts.subscription : activeSubscription();
  const emailVerified = opts.emailVerified ?? true;
  const found = opts.deadlineFound ?? true;
  const calls: Call[] = [];
  const generatedRecord = deadlineRecord({
    isAutoGenerated: true,
    generatedKind: opts.generatedKind ?? 'CHARITY_ANNUAL_REPORT',
    description: 'PRIVATE_PROFILE_DESCRIPTION',
    generatedKey: 'PRIVATE_GENERATED_KEY',
    generationFingerprint: 'PRIVATE_FINGERPRINT',
    generationSource: { note: 'PRIVATE_SOURCE' },
    generationInputs: { contactEmail: 'PRIVATE_INPUT' },
    profileRuleKey: 'PRIVATE_PROFILE_RULE',
    supersededById: 'PRIVATE_SUCCESSOR',
  });

  const app = Fastify({ logger: false });
  const models = {
    ...authModels(role, subscription, emailVerified),
    ...(opts.clientKind ? { authSession: { findFirst: async () => ({
      id: 'sess-1', clientKind: opts.clientKind, accessLevel: 'ADMIN',
    }) } } : {}),
    deadline: {
      findMany: async (args: unknown) => {
        calls.push({ name: 'deadline.findMany', args });
        return opts.generatedDeadline && opts.generatedKind !== 'LEGACY_UNVERIFIED' ? [generatedRecord] : [];
      },
      count: async (args: unknown) => {
        calls.push({ name: 'deadline.count', args });
        return 0;
      },
      create: async (args: { data: Record<string, unknown> }) => {
        calls.push({ name: 'deadline.create', args });
        return deadlineRecord({ id: 'new-id', ...args.data });
      },
      findFirst: async (args: { where: { id?: string; organisationId: string; isAutoGenerated?: boolean } }) => {
        calls.push({ name: 'deadline.findFirst', args });
        return found && (!args.where.isAutoGenerated || (opts.generatedDeadline && opts.generatedKind !== 'LEGACY_UNVERIFIED'))
          ? opts.generatedDeadline ? { ...generatedRecord, id: args.where.id } : deadlineRecord({ id: args.where.id, organisationId: args.where.organisationId })
          : null;
      },
      findUniqueOrThrow: async (args: { where: { id: string } }) => {
        calls.push({ name: 'deadline.findUniqueOrThrow', args });
        return deadlineRecord({ id: args.where.id });
      },
      update: async (args: { where: { id: string }; data: Record<string, unknown> }) => {
        calls.push({ name: 'deadline.update', args });
        const definedData = Object.fromEntries(
          Object.entries(args.data).filter(([, value]) => value !== undefined),
        );
        return deadlineRecord({ id: args.where.id, ...definedData });
      },
      updateMany: async (args: { data: Record<string, unknown> }) => {
        calls.push({ name: 'deadline.updateMany', args });
        return { count: 1 };
      },
      delete: async (args: unknown) => {
        calls.push({ name: 'deadline.delete', args });
        return {};
      },
    },
    deadlineChangeAudit: {
      create: async (args: unknown) => { calls.push({ name: 'deadlineChangeAudit.create', args }); return {}; },
      findMany: async (args: unknown) => {
        calls.push({ name: 'deadlineChangeAudit.findMany', args });
        return [{ id: 'audit-1', organisationId: 'org-1', deadlineId: 'd1', actorUserId: 'u1',
          action: 'ARCHIVE', previousState: 'OPEN', nextState: 'ARCHIVED', changedFields: ['archivedAt'] }];
      },
    },
  };
  app.decorate('prisma', {
    ...models,
    $transaction: async (callback: (tx: typeof models) => Promise<unknown>) => callback(models),
  } as never);

  return { app, calls };
}

test('Admin connector cannot read deadline change history through the direct API', async () => {
  await withApp({ clientKind: 'MCP_CONNECTOR' }, async ({ app, calls }) => {
    const response = await app.inject({ method: 'GET', url: '/audit', headers: { authorization: tokenFor('ADMIN') } });
    assert.equal(response.statusCode, 403);
    assert.equal(response.json().code, 'WEB_SESSION_REQUIRED');
    assert.equal(calls.some((call) => call.name === 'deadlineChangeAudit.findMany'), false);
  });
});

async function withApp(
  opts: Parameters<typeof buildApp>[0],
  fn: (ctx: { app: Awaited<ReturnType<typeof buildApp>>['app']; calls: Call[] }) => Promise<void>,
) {
  const { app, calls } = buildApp(opts);
  await app.register(deadlineRoutes);
  try {
    await fn({ app, calls });
  } finally {
    await app.close();
  }
}

// ── deadlines-tenant-isolation-5 ──
test('PATCH/DELETE /:id for a deadline owned by another organisation returns 404 DEADLINE_NOT_FOUND without writing', async () => {
  await withApp({ role: 'ADMIN', deadlineFound: false }, async ({ app, calls }) => {
    const patch = await app.inject({
      method: 'PATCH',
      url: '/d-other',
      headers: { authorization: tokenFor('ADMIN') },
      payload: { expectedUpdatedAt: EXPECTED_UPDATED_AT, title: 'Hijacked' },
    });
    assert.equal(patch.statusCode, 404);
    assert.equal(patch.json().code, 'DEADLINE_NOT_FOUND');

    const del = await app.inject({
      method: 'DELETE',
      url: '/d-other',
      headers: { authorization: tokenFor('ADMIN') },
      payload: { expectedUpdatedAt: EXPECTED_UPDATED_AT },
    });
    assert.equal(del.statusCode, 404);
    assert.equal(del.json().code, 'DEADLINE_NOT_FOUND');

    // The lookup must be scoped to the caller's organisation.
    const lookup = calls.find((c) => c.name === 'deadline.findFirst');
    assert.deepEqual((lookup?.args as { where: unknown }).where, {
      id: 'd-other',
      organisationId: 'org-1',
      archivedAt: null,
    });
    assert.equal(calls.some((c) => c.name === 'deadline.updateMany'), false);
    assert.equal(calls.some((c) => c.name === 'deadline.delete'), false);
  });
});

