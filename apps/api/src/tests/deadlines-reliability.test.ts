test('a MEMBER cannot read a manually authored or legacy deadline by direct ID', async () => {
  await withApp({ role: 'MEMBER' }, async ({ app, calls }) => {
    const res = await app.inject({ method: 'GET', url: '/d1', headers: { authorization: tokenFor('MEMBER') } });
    assert.equal(res.statusCode, 404);
    assert.deepEqual((calls.find((call) => call.name === 'deadline.findFirst')?.args as { where: unknown }).where,
      { id: 'd1', organisationId: 'org-1', isAutoGenerated: true, generatedKind: { not: 'LEGACY_UNVERIFIED' } });
  });
  await withApp({ role: 'MEMBER', generatedDeadline: true }, async ({ app, calls }) => {
    const res = await app.inject({ method: 'GET', url: '/d1', headers: { authorization: tokenFor('MEMBER') } });
    assert.equal(res.statusCode, 200);
    for (const response of [
      res,
      await app.inject({ method: 'GET', url: '/', headers: { authorization: tokenFor('MEMBER') } }),
      await app.inject({ method: 'GET', url: '/history', headers: { authorization: tokenFor('MEMBER') } }),
    ]) {
      assert.equal(response.statusCode, 200);
      assert.equal(/PRIVATE_/u.test(response.body), false, 'Member responses must not copy profile snapshots or descriptions');
      const payload = response.json().data;
      const record = Array.isArray(payload) ? payload[0] : Array.isArray(payload?.data) ? payload.data[0] : payload;
      assert.equal(record.description, null);
      assert.equal(record.generationInputs, null);
      assert.equal(record.generationSource, null);
      assert.equal(record.generatedKey, null);
      assert.equal(record.supersededById, null);
    }
    for (const call of calls.filter((item) => item.name === 'deadline.findMany' || item.name === 'deadline.findFirst')) {
      const select = (call.args as { select?: Record<string, boolean> }).select;
      assert.ok(select, `${call.name} must project Member fields at the database`);
      for (const field of ['description', 'generationInputs', 'generationSource', 'generatedKey',
        'generationFingerprint', 'profileRuleKey', 'supersededById']) {
        assert.equal(select[field], undefined, `${field} must not be fetched for a Member`);
      }
      assert.equal(select.title, true);
      assert.equal(select.dueDate, true);
    }
  });
  await withApp({ role: 'MEMBER', generatedDeadline: true, generatedKind: 'LEGACY_UNVERIFIED' }, async ({ app }) => {
    const res = await app.inject({ method: 'GET', url: '/d1', headers: { authorization: tokenFor('MEMBER') } });
    assert.equal(res.statusCode, 404);
  });
  await withApp({ role: 'ADMIN' }, async ({ app }) => {
    const res = await app.inject({ method: 'GET', url: '/d1', headers: { authorization: tokenFor('ADMIN') } });
    assert.equal(res.statusCode, 200);
  });
});

// ── deadlines-auth-session-9 ──
test('deadline routes require authentication', async () => {
  // Case 1: no Authorization header at all.
  await withApp({}, async ({ app, calls }) => {
    const res = await app.inject({ method: 'GET', url: '/' });
    assert.equal(res.statusCode, 401);
    assert.equal(res.json().code, 'UNAUTHORIZED');
    assert.equal(calls.some((c) => c.name.startsWith('deadline.')), false);
  });

  // Case 2: a valid token whose session was revoked (authSession.findFirst => null).
  const revokedApp = Fastify({ logger: false });
  const revokedCalls: Call[] = [];
  revokedApp.decorate('prisma', {
    authSession: { findFirst: async () => null },
    user: { findUnique: async () => ({ id: 'u1', organisationId: 'org-1', role: 'ADMIN', emailVerified: true }) },
    subscription: { findUnique: async () => activeSubscription() },
    deadline: {
      findMany: async () => {
        revokedCalls.push({ name: 'deadline.findMany', args: {} });
        return [];
      },
    },
  } as never);
  await revokedApp.register(deadlineRoutes);
  try {
    const res = await revokedApp.inject({
      method: 'GET',
      url: '/',
      headers: { authorization: tokenFor('ADMIN') },
    });
    assert.equal(res.statusCode, 401);
    assert.equal(res.json().code, 'UNAUTHORIZED');
    assert.equal(revokedCalls.length, 0, 'revoked session must not reach the handler');
  } finally {
    await revokedApp.close();
  }
});

