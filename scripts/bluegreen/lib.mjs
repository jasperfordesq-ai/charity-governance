import { readFileSync, writeFileSync, renameSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

export const COLORS = ['blue', 'green'];

// Cap at 50 entries: unbounded status history grows forever on a long-lived VM;
// 50 entries cover a full deploy's phases many times over.
const STATUS_HISTORY_LIMIT = 50;

export function otherColor(color) {
  if (color === 'blue') return 'green';
  if (color === 'green') return 'blue';
  throw new Error(`Invalid color: ${color}. Must be 'blue' or 'green'.`);
}

export function readState(stateDir) {
  const stateFile = join(stateDir, 'state.json');
  try {
    const content = readFileSync(stateFile, 'utf8');
    return JSON.parse(content);
  } catch (err) {
    // If file is missing, return null (no error flag)
    if (err.code === 'ENOENT') {
      return null;
    }
    // Parse error or read error: return corrupt flag
    if (err instanceof SyntaxError || err.code === 'ERR_INVALID_ARG_TYPE') {
      return { corrupt: true };
    }
    // Other IO errors (permissions, etc.): flag as corrupt with error detail
    return { corrupt: true, error: err.message };
  }
}

export function writeState(stateDir, state) {
  mkdirSync(stateDir, { recursive: true });
  const stateFile = join(stateDir, 'state.json');
  const tmpFile = join(stateDir, 'state.json.tmp');

  // Write to temp file
  writeFileSync(tmpFile, JSON.stringify(state, null, 2));

  // Atomic rename
  renameSync(tmpFile, stateFile);
}

export function renderUpstreams(color) {
  if (color !== 'blue' && color !== 'green') {
    throw new Error(`Invalid color: ${color}. Must be 'blue' or 'green'.`);
  }

  return [
    '# Generated by scripts/bluegreen-deploy.mjs — do not edit by hand.',
    '# The engine writes the live colour\'s upstreams and gracefully reloads Caddy.',
    `reverse_proxy /api/* api-${color}:3002`,
    `reverse_proxy web-${color}:3003`,
    '',
  ].join('\n');
}

export function releaseDirFor(stateDir, commit) {
  return join(stateDir, 'releases', commit);
}

export function prunePlan(releases, keep = 3, activeCommit) {
  // releases is an array of {commit, mtime}
  // returns array of commits to delete
  // keeps newest `keep` releases
  // but NEVER deletes the active commit

  if (!Array.isArray(releases)) {
    return [];
  }

  // Sort by mtime descending (newest first)
  const sorted = [...releases].sort((a, b) => (b.mtime ?? 0) - (a.mtime ?? 0));

  // Keep the newest `keep` releases
  const toKeep = new Set(sorted.slice(0, keep).map(r => r.commit));

  // Also keep the active commit if provided
  if (activeCommit) {
    toKeep.add(activeCommit);
  }

  // Return all commits that are NOT in the toKeep set
  const toDelete = releases
    .map(r => r.commit)
    .filter(commit => !toKeep.has(commit));

  return toDelete;
}

export function deployStatus(stateDir) {
  const statusFile = join(stateDir, 'deploy-status.json');
  try {
    const content = readFileSync(statusFile, 'utf8');
    return JSON.parse(content);
  } catch (err) {
    // If file is missing or corrupt, return null
    if (err.code === 'ENOENT') {
      return null;
    }
    // If file is corrupt (parse error), return null
    return null;
  }
}

export function writeDeployStatus(stateDir, phase, detail) {
  mkdirSync(stateDir, { recursive: true });
  const statusFile = join(stateDir, 'deploy-status.json');
  const tmpFile = join(stateDir, 'deploy-status.json.tmp');

  // Read existing status or create new
  let status = deployStatus(stateDir) || { history: [] };

  // Ensure history is an array
  if (!Array.isArray(status.history)) {
    status.history = [];
  }

  // Add new entry
  const entry = {
    timestamp: new Date().toISOString(),
    phase,
    detail,
  };

  status.history.push(entry);

  // Keep only the last 50 entries
  if (status.history.length > STATUS_HISTORY_LIMIT) {
    status.history = status.history.slice(-STATUS_HISTORY_LIMIT);
  }

  // Update the status object with latest phase and detail
  status.phase = phase;
  status.detail = detail;
  status.timestamp = entry.timestamp;

  // Write to temp file
  writeFileSync(tmpFile, JSON.stringify(status, null, 2));

  // Atomic rename
  renameSync(tmpFile, statusFile);
}
